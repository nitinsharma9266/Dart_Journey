void main() {
  print("========== RELATIONAL OPERATORS ==========\n");

  int a = 20;
  int b = 10;

  print("a = $a");
  print("b = $b\n");

  // Greater Than
  print("a > b  : ${a > b}");

  // Less Than
  print("a < b  : ${a < b}");

  // Greater Than or Equal To
  print("a >= b : ${a >= b}");

  // Less Than or Equal To
  print("a <= b : ${a <= b}");

  // Equal To
  print("a == b : ${a == b}");

  // Not Equal To
  print("a != b : ${a != b}");

  print("\n==========================================");
}